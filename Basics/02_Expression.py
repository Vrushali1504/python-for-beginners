# Expression and Statements

# Statement
# A statement performs an action

x = 10  # assigning value to variable
print(x)  # printing output


# Expression
# An expression produces a value | An expression is a combination of values, variables, and operators that produces a result.

5 + 3  # result is 8
x * 2  # result is 20
"Hello" + " Python"  # result is "Hello Python"


# Statement with expression

y = 5 + 3

# Here:
# y = 5 + 3  -> statement
# 5 + 3      -> expression
# result of expression is 8
