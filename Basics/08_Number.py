# Number with built in function

"""
Numbers in Python include integers and floating-point values used for calculations.
They support arithmetic operations like addition and multiplication. Numbers are one of the most basic data types.
"""

# ==============
# Integer (int)
# ==============

a = 10
print("Integer:")
print(a)
print(type(a))  # built-in function: type()
print(abs(-10))  # built-in function: abs()


# ==============
# Float (float)
# ==============

b = 10.5
print("\nFloat:")
print(b)
print(type(b))  # built-in function: type()
print(round(b))  # built-in function: round()


# ==================
# Complex (complex)
# ==================

c = 2 + 3j
print("\nComplex:")
print(c)
print(type(c))  # built-in function: type()
print(abs(c))  # built-in function: abs() (magnitude)
